// setupGin initializes the Gin engine with logging, recovery, and custom middleware
func setupGin() {
	// Initialize ginEngine first
	ginEngine = gin.New()

	// Register the StripMainPrefix middleware first

	// Configure CORS
	setupCors()

	gin.DefaultWriter = io.MultiWriter(os.Stdout)
	// Release mode for Production, Test, Debug mode while Development
	gin.SetMode(gin.ReleaseMode)
	//ForceConsoleColor force color output in the console.
	gin.ForceConsoleColor()

	ginEngine.Use(
		gin.LoggerWithWriter(gin.DefaultWriter, "/main"),
		gin.Recovery(),
	)
	ginEngine.Use(middlewares.HandlePanic)
	ginEngine.Use(middlewares.RequestIDMiddleware())
	ginEngine.Use(middlewares.SecurityHeadersMiddleware())
}

// setupCors configures CORS settings for the Gin engine. Only origins in
// constants.CORS_ALLOWED_ORIGINS are reflected back - a StackHawk DAST scan
// flagged the previous unconditional "*" as a Cross-Domain Misconfiguration
// (CWE-264), since it let any third-party site read responses from this API's
// unauthenticated endpoints.
//
// On staging only, http://localhost:3000 is additionally allowed so the
// frontend can be run locally against the staging API during development -
// never added in production, where only the real deployed origins apply.
// Gated on the request's own Host header (the staging domain) rather than
// cfg.AppEnv: AppEnv is a deploy-time secret this process can't be made to
// print for verification, and in practice it didn't match the "staging"
// string this assumed - Host is directly observable and already the
// definitive signal distinguishing the staging deployment from production
// (they're separate Cloud Run services on separate domains).
func setupCors() {
	const stagingHost = "jiab-staging.coke2home.com"

	ginEngine.Use(func(c *gin.Context) {
		allowedOrigins := constants.CORS_ALLOWED_ORIGINS
		if c.Request.Host == stagingHost {
			allowedOrigins = make(map[string]bool, len(constants.CORS_ALLOWED_ORIGINS)+1)
			for origin := range constants.CORS_ALLOWED_ORIGINS {
				allowedOrigins[origin] = true
			}
			allowedOrigins["http://localhost:3000"] = true
		}

		origin := c.Request.Header.Get("Origin")
		if allowedOrigins[origin] {
			c.Writer.Header().Set("Access-Control-Allow-Origin", origin)
			c.Writer.Header().Set("Vary", "Origin")
		}
		c.Writer.Header().Set("Access-Control-Allow-Methods", "GET, POST, PUT, PATCH, DELETE, OPTIONS")
		c.Writer.Header().Set("Access-Control-Allow-Headers", "*")
		c.Writer.Header().Set("Access-Control-Max-Age", "86400")
		if c.Request.Method == "OPTIONS" {
			c.AbortWithStatus(200)
			return
		}
		c.Next()
	})
}

// startServer starts the HTTP server on the specified port
func startServer(portFlag string) {
	cfg := config.GetConfig()

	var port string
	if portFlag != "" {
		port = portFlag
		logrus.Info("Using port from flag: " + port)
	} else if cfg.AppPort != "" {
		port = cfg.AppPort
		logrus.Info("Using port from config: " + port)
	} else {
		port = "8080"
		logrus.Info("Using default port: " + port)
	}

	server := &http.Server{
		Addr:              ":" + port,
		Handler:           ginEngine,
		ReadTimeout:       30 * time.Second,
		WriteTimeout:      30 * time.Second,
		ReadHeaderTimeout: 30 * time.Second,
		IdleTimeout:       120 * time.Second,
	}

	quit := make(chan os.Signal, 1)
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)

	go func() {
		logrus.Info("Starting the server on :" + port)
		if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			logrus.Fatalf("Server failed to start: %v", err)
		}
	}()

	<-quit
	logrus.Info("Shutting down server...")

	if cfg.SSHConfig.UseSSH == "true" {
		vendors.CloseTunnel()
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	if err := server.Shutdown(ctx); err != nil {
		logrus.Errorf("Server forced to shutdown: %v", err)
	} else {
		logrus.Info("Server exited gracefully")
	}
}

